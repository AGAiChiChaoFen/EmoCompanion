#!/usr/bin/env bash
set -euo pipefail

# One-click launcher for packaged layout:
# /mnt1/userhome/lishaoyuan/wbg/EmoCompanion/
#   ├─ ditto-talkinghead/
#   ├─ LiveTalking/
#   └─ PersonaVLM/

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="${PROJECT_ROOT:-$SCRIPT_DIR}"

# All runtime values, including secrets, are kept in one tracked config file.
CONFIG_FILE="${CONFIG_FILE:-$PROJECT_ROOT/config.env}"
if [[ ! -f "$CONFIG_FILE" ]]; then
  echo "[ERROR] config file not found: $CONFIG_FILE"
  exit 1
fi
# shellcheck disable=SC1090
source "$CONFIG_FILE"

case "$ASR_PROVIDER" in
  qwenaudio)
    CUSTOM_ASR_API_URL="$QWENAUDIO_API_URL"
    CUSTOM_ASR_TIMEOUT_S="$QWENAUDIO_TIMEOUT_S"
    CUSTOM_ASR_FILE_FIELD="$QWENAUDIO_FILE_FIELD"
    CUSTOM_ASR_SEND_SESSION="$QWENAUDIO_SEND_SESSION"
    CUSTOM_ASR_SEND_MODE="$QWENAUDIO_SEND_MODE"
    ;;
  *)
    echo "[ERROR] unsupported ASR_PROVIDER: $ASR_PROVIDER"
    exit 1
    ;;
esac

case "$LLM_PROVIDER" in
  personavlm)
    CUSTOM_EMOLLM_API_URL="$PERSONAVLM_EMOLLM_API_URL"
    CUSTOM_EMOLLM_TIMEOUT_S="$PERSONAVLM_EMOLLM_TIMEOUT_S"
    CUSTOM_EMOLLM_AUTH_TOKEN=""
    ;;
  emotionllama)
    CUSTOM_EMOLLM_API_URL="$EMOTIONLLAMA_API_URL"
    CUSTOM_EMOLLM_TIMEOUT_S="$EMOTIONLLAMA_TIMEOUT_S"
    CUSTOM_EMOLLM_AUTH_TOKEN="$EMOTIONLLAMA_AUTH_TOKEN"
    ;;
  *)
    echo "[ERROR] unsupported LLM_PROVIDER: $LLM_PROVIDER"
    exit 1
    ;;
esac

if [[ -z "${DASHSCOPE_API_KEY:-}" && -n "${QWEN_API_KEY:-}" ]]; then
  export DASHSCOPE_API_KEY="$QWEN_API_KEY"
fi

# TURN_URL is derived from the configured coturn host and transport flags.
turn_urls=()
if [[ "$TURN_ENABLE_UDP" == "1" ]]; then
  turn_urls+=("turn:${TURN_HOST}:${TURN_PORT}?transport=udp")
fi
if [[ "$TURN_ENABLE_TCP" == "1" ]]; then
  turn_urls+=("turn:${TURN_HOST}:${TURN_PORT}?transport=tcp")
fi
if [[ "$TURN_ENABLE_TLS" == "1" ]]; then
  turn_urls+=("turns:${TURN_HOST}:${TURN_TLS_PORT}?transport=tcp")
fi
TURN_URL="$(IFS=,; echo "${turn_urls[*]}")"

if [[ -z "$TURN_URL" ]]; then
  echo "[ERROR] TURN_URL is empty. Set TURN_URL directly or enable TURN transport flags."
  exit 1
fi
if [[ "$ICE_TRANSPORT_POLICY" == "relay" && ( -z "$TURN_USERNAME" || -z "$TURN_PASSWORD" ) ]]; then
  echo "[ERROR] ICE_TRANSPORT_POLICY=relay requires TURN_USERNAME and TURN_PASSWORD."
  echo "[ERROR] Set TURN_USERNAME/TURN_PASSWORD in the script defaults or export them before running this script."
  exit 1
fi

if [[ ! -f "$CONDA_SH" ]]; then
  echo "[ERROR] conda.sh not found: $CONDA_SH"
  exit 1
fi
if [[ ! -d "$TALKINGHEAD_DIR" ]]; then
  echo "[ERROR] talkinghead dir not found: $TALKINGHEAD_DIR"
  exit 1
fi
if [[ ! -d "$LIVETALKING_DIR" ]]; then
  echo "[ERROR] livetalking dir not found: $LIVETALKING_DIR"
  exit 1
fi
if [[ "$PERSONA_API_ENABLE" == "1" && ! -d "$PERSONAVLM_DIR" ]]; then
  echo "[ERROR] PersonaVLM dir not found: $PERSONAVLM_DIR"
  exit 1
fi
if [[ ! -f "$LIVETALKING_DIR/app.py" ]]; then
  echo "[ERROR] app.py not found: $LIVETALKING_DIR/app.py"
  exit 1
fi
if [[ "$PERSONA_API_ENABLE" == "1" && ! -f "$PERSONAVLM_DIR/api_server.py" ]]; then
  echo "[ERROR] PersonaVLM api_server.py not found: $PERSONAVLM_DIR/api_server.py"
  exit 1
fi
if [[ ! -f "$DITTO_SOURCE_PATH" ]]; then
  echo "[ERROR] DITTO_SOURCE_PATH not found: $DITTO_SOURCE_PATH"
  exit 1
fi

# shellcheck disable=SC1090
source "$CONDA_SH"
conda activate "$CONDA_ENV_NAME"

export CUDA_VISIBLE_DEVICES
export LD_LIBRARY_PATH="$TENSORRT_LIB_DIR:${LD_LIBRARY_PATH:-}"
export LLM_NONSTREAM_DELTA_INTERVAL_MS
export CUSTOM_ASR_API_URL
export CUSTOM_ASR_TIMEOUT_S
export CUSTOM_ASR_FILE_FIELD
export CUSTOM_ASR_SEND_SESSION
export CUSTOM_ASR_SEND_MODE
export CUSTOM_EMOLLM_API_URL
export CUSTOM_EMOLLM_TIMEOUT_S
if [[ -n "$CUSTOM_EMOLLM_AUTH_TOKEN" ]]; then
  export CUSTOM_EMOLLM_AUTH_TOKEN
fi
export CUSTOM_EMOLLM_DEFAULT_EMOTION
export CUSTOM_EMOLLM_SESSION_ID
export CUSTOM_EMOLLM_DELTA_INTERVAL_MS
export PERSONA_API_DEFAULT_USER
export PERSONA_API_OUTPUT_ROOT
export PERSONA_API_MODEL_PATH
export PERSONA_API_LOG_LEVEL
export PERSONA_API_CORS_ORIGINS
export PERSONA_API_MAX_BODY_BYTES
export PERSONA_API_REASONING_MODE
export PERSONA_API_FORCE_RETRIEVE

echo "[INFO] PROJECT_ROOT=$PROJECT_ROOT"
echo "[INFO] TALKINGHEAD_DIR=$TALKINGHEAD_DIR"
echo "[INFO] LIVETALKING_DIR=$LIVETALKING_DIR"
echo "[INFO] PERSONAVLM_DIR=$PERSONAVLM_DIR"
echo "[INFO] CONDA_ENV_NAME=$CONDA_ENV_NAME"
echo "[INFO] CUDA_VISIBLE_DEVICES=$CUDA_VISIBLE_DEVICES"
echo "[INFO] DITTO_DATA_ROOT=$DITTO_DATA_ROOT"
echo "[INFO] DITTO_CFG_PKL=$DITTO_CFG_PKL"
echo "[INFO] DITTO_SOURCE_PATH=$DITTO_SOURCE_PATH"
echo "[INFO] LISTEN_PORT=$LISTEN_PORT"
echo "[INFO] TURN_HOST=$TURN_HOST"
echo "[INFO] TURN_PORT=$TURN_PORT"
echo "[INFO] TURN_TLS_PORT=$TURN_TLS_PORT"
echo "[INFO] TURN_ENABLE_UDP=$TURN_ENABLE_UDP"
echo "[INFO] TURN_ENABLE_TCP=$TURN_ENABLE_TCP"
echo "[INFO] TURN_ENABLE_TLS=$TURN_ENABLE_TLS"
echo "[INFO] ICE_TRANSPORT_POLICY=$ICE_TRANSPORT_POLICY"
echo "[INFO] PREFER_H264=$PREFER_H264"
echo "[INFO] TURN_URL=$TURN_URL"
echo "[INFO] TTS_MODE=$TTS_MODE"
echo "[INFO] ASR_PROVIDER=$ASR_PROVIDER"
echo "[INFO] ASR_BACKEND=$ASR_BACKEND"
echo "[INFO] ASR_CUSTOM_HANDLER=$ASR_CUSTOM_HANDLER"
echo "[INFO] PERSONA_API_ENABLE=$PERSONA_API_ENABLE"
echo "[INFO] PERSONA_API_URL=http://$PERSONA_API_HOST:$PERSONA_API_PORT"
echo "[INFO] PERSONA_API_READY_URL=http://$PERSONA_API_HEALTH_HOST:$PERSONA_API_PORT/ready"
echo "[INFO] PERSONA_API_DEFAULT_USER=$PERSONA_API_DEFAULT_USER"
echo "[INFO] PERSONA_API_PRELOAD_MODEL=$PERSONA_API_PRELOAD_MODEL"
echo "[INFO] CUSTOM_ASR_API_URL=$CUSTOM_ASR_API_URL"
echo "[INFO] CUSTOM_EMOLLM_API_URL=$CUSTOM_EMOLLM_API_URL"
echo "[INFO] LLM_PROVIDER=$LLM_PROVIDER"
echo "[INFO] DEEPFACE_ENABLE=$DEEPFACE_ENABLE"
echo "[INFO] DEEPFACE_API_URL=$DEEPFACE_API_URL"
echo "[INFO] DEEPFACE_ANALYZE_EVERY_N=$DEEPFACE_ANALYZE_EVERY_N"
echo "[INFO] LIGHTRAG_ENABLE=$LIGHTRAG_ENABLE"
echo "[INFO] LIGHTRAG_BASE_URL=$LIGHTRAG_BASE_URL"
echo "[INFO] WEBRTC_FINAL_ASR_BACKEND=$WEBRTC_FINAL_ASR_BACKEND"
echo "[INFO] WEBRTC_FINAL_ASR_STRICT_FAILURE=$WEBRTC_FINAL_ASR_STRICT_FAILURE"
echo "[INFO] WEBRTC_FINAL_ASR_CLOUD_VERIFY_ENABLE=$WEBRTC_FINAL_ASR_CLOUD_VERIFY_ENABLE"
echo "[INFO] WEBRTC_FINAL_ASR_CLOUD_VERIFY_BACKEND=$WEBRTC_FINAL_ASR_CLOUD_VERIFY_BACKEND"
echo "[INFO] WEBRTC_FINAL_ASR_CLOUD_VERIFY_SIMILARITY=$WEBRTC_FINAL_ASR_CLOUD_VERIFY_SIMILARITY"
echo "[INFO] WEBRTC_FINAL_ASR_CLOUD_VERIFY_SHORT_TEXT_CHARS=$WEBRTC_FINAL_ASR_CLOUD_VERIFY_SHORT_TEXT_CHARS"
echo "[INFO] WEBRTC_FINAL_ASR_CLOUD_VERIFY_MIN_CLOUD_CHARS=$WEBRTC_FINAL_ASR_CLOUD_VERIFY_MIN_CLOUD_CHARS"
echo "[INFO] WEBRTC_FINAL_ASR_CLOUD_VERIFY_REPLACE_WITH_CLOUD=$WEBRTC_FINAL_ASR_CLOUD_VERIFY_REPLACE_WITH_CLOUD"
echo "[INFO] WEBRTC_ASR_SPEECH_LEVEL=$WEBRTC_ASR_SPEECH_LEVEL"
echo "[INFO] WEBRTC_ASR_MIN_PARTIAL_SPEECH_FRAMES=$WEBRTC_ASR_MIN_PARTIAL_SPEECH_FRAMES"
echo "[INFO] WEBRTC_ASR_MIN_FINAL_SPEECH_FRAMES=$WEBRTC_ASR_MIN_FINAL_SPEECH_FRAMES"
echo "[INFO] WEBRTC_ASR_MIN_FINAL_PEAK_LEVEL=$WEBRTC_ASR_MIN_FINAL_PEAK_LEVEL"
echo "[INFO] WEBRTC_ASR_DROP_WHILE_AVATAR_SPEAKING=$WEBRTC_ASR_DROP_WHILE_AVATAR_SPEAKING"
echo "[INFO] WEBRTC_ASR_ECHO_GUARD_MS=$WEBRTC_ASR_ECHO_GUARD_MS"
echo "[INFO] WEBRTC_ASR_ECHO_SIMILARITY=$WEBRTC_ASR_ECHO_SIMILARITY"
echo "[INFO] FUNASR_MODEL=$FUNASR_MODEL"
echo "[INFO] LLM_BACKEND=$LLM_BACKEND"
echo "[INFO] LLM_NONSTREAM_DELTA_INTERVAL_MS=$LLM_NONSTREAM_DELTA_INTERVAL_MS"
echo "[INFO] CUSTOM_ASR_API_URL=$CUSTOM_ASR_API_URL"
echo "[INFO] CUSTOM_EMOLLM_API_URL=$CUSTOM_EMOLLM_API_URL"
echo "[INFO] CUSTOM_EMOLLM_DELTA_INTERVAL_MS=$CUSTOM_EMOLLM_DELTA_INTERVAL_MS"
echo "[INFO] LLM_CUSTOM_HANDLER=$LLM_CUSTOM_HANDLER"
if [[ -n "${DASHSCOPE_API_KEY:-}" ]]; then
  echo "[INFO] DASHSCOPE_API_KEY=SET"
else
  echo "[INFO] DASHSCOPE_API_KEY=EMPTY"
fi

if [[ "$PERSONA_API_PRELOAD_MODEL" == "1" ]]; then
  PERSONA_PRELOAD_ARGS=(--preload-model)
else
  PERSONA_PRELOAD_ARGS=()
fi

if [[ "$WEBRTC_FINAL_ASR_STRICT_FAILURE" == "1" ]]; then
  WEBRTC_FINAL_ASR_STRICT_ARGS=(--WEBRTC_FINAL_ASR_STRICT_FAILURE)
else
  WEBRTC_FINAL_ASR_STRICT_ARGS=()
fi
read -r -a DITTO_CHUNKSIZE_ARGS <<< "$DITTO_CHUNKSIZE"

if [[ "$DEEPFACE_ENABLE" == "1" ]]; then
  DEEPFACE_ARGS=(
    --DEEPFACE_ENABLE
    --DEEPFACE_API_URL "$DEEPFACE_API_URL"
    --DEEPFACE_TIMEOUT_S "$DEEPFACE_TIMEOUT_S"
    --DEEPFACE_ANALYZE_EVERY_N "$DEEPFACE_ANALYZE_EVERY_N"
    --DEEPFACE_CACHE_MAX_AGE_MS "$DEEPFACE_CACHE_MAX_AGE_MS"
  )
else
  DEEPFACE_ARGS=()
fi

if [[ "$TTS_MODE" == "qwen3tts" ]] && [[ -z "$QWEN_API_KEY" ]] && [[ -z "${DASHSCOPE_API_KEY:-}" ]]; then
  echo "[ERROR] qwen3tts requires QWEN_API_KEY or DASHSCOPE_API_KEY"
  exit 1
fi

PERSONA_API_PID=""
cleanup() {
  if [[ -n "${PERSONA_API_PID:-}" ]] && kill -0 "$PERSONA_API_PID" 2>/dev/null; then
    echo "[INFO] stopping PersonaVLM API pid=$PERSONA_API_PID"
    kill "$PERSONA_API_PID" 2>/dev/null || true
    wait "$PERSONA_API_PID" 2>/dev/null || true
  fi
}
trap cleanup EXIT INT TERM

if [[ "$PERSONA_API_ENABLE" == "1" ]]; then
  mkdir -p "$(dirname "$PERSONA_API_LOG_FILE")"
  echo "[INFO] starting PersonaVLM API: http://$PERSONA_API_HOST:$PERSONA_API_PORT"
  (
    cd "$PERSONAVLM_DIR"
    python api_server.py \
      --host "$PERSONA_API_HOST" \
      --port "$PERSONA_API_PORT" \
      --output-root "$PERSONA_API_OUTPUT_ROOT" \
      --model-path "$PERSONA_API_MODEL_PATH" \
      --log-level "$PERSONA_API_LOG_LEVEL" \
      "${PERSONA_PRELOAD_ARGS[@]}"
  ) >"$PERSONA_API_LOG_FILE" 2>&1 &
  PERSONA_API_PID=$!
  echo "[INFO] PersonaVLM API pid=$PERSONA_API_PID log=$PERSONA_API_LOG_FILE"

  PERSONA_READY=0
  for ((i = 1; i <= PERSONA_API_STARTUP_TIMEOUT_S; i++)); do
    if python -c "import urllib.request; urllib.request.urlopen('http://$PERSONA_API_HEALTH_HOST:$PERSONA_API_PORT/ready', timeout=1).read()" >/dev/null 2>&1; then
      PERSONA_READY=1
      break
    fi
    if ! kill -0 "$PERSONA_API_PID" 2>/dev/null; then
      echo "[ERROR] PersonaVLM API exited early. Recent log:"
      tail -n 80 "$PERSONA_API_LOG_FILE" || true
      exit 1
    fi
    sleep 1
  done

  if [[ "$PERSONA_READY" != "1" ]]; then
    echo "[ERROR] PersonaVLM API did not become ready within ${PERSONA_API_STARTUP_TIMEOUT_S}s"
    tail -n 80 "$PERSONA_API_LOG_FILE" || true
    exit 1
  fi
  echo "[INFO] PersonaVLM API readiness check passed"
fi

cd "$LIVETALKING_DIR"

python app.py \
  --model "$LIVE_TALKING_MODEL" \
  --listenport "$LISTEN_PORT" \
  --transport "$LIVE_TALKING_TRANSPORT" \
  --tts "$TTS_MODE" \
  --QWEN_API_KEY "$QWEN_API_KEY" \
  --QWEN_MODEL "$QWEN_MODEL" \
  --QWEN_BASE_URL "$QWEN_BASE_URL" \
  --QWEN_LANGUAGE_TYPE "$QWEN_LANGUAGE_TYPE" \
  --asr_backend "$ASR_BACKEND" \
  --ASR_CUSTOM_HANDLER "$ASR_CUSTOM_HANDLER" \
  --FUNASR_API_KEY "$FUNASR_API_KEY" \
  --FUNASR_MODEL "$FUNASR_MODEL" \
  --FUNASR_BASE_URL "$FUNASR_BASE_URL" \
  --FUNASR_SAMPLE_RATE "$FUNASR_SAMPLE_RATE" \
  --FUNASR_LANGUAGE_HINT "$FUNASR_LANGUAGE_HINT" \
  --FUNASR_MAX_SENTENCE_SILENCE "$FUNASR_MAX_SENTENCE_SILENCE" \
  --WEBRTC_FINAL_ASR_BACKEND "$WEBRTC_FINAL_ASR_BACKEND" \
  --WEBRTC_FINAL_ASR_CLOUD_VERIFY_ENABLE "$WEBRTC_FINAL_ASR_CLOUD_VERIFY_ENABLE" \
  --WEBRTC_FINAL_ASR_CLOUD_VERIFY_BACKEND "$WEBRTC_FINAL_ASR_CLOUD_VERIFY_BACKEND" \
  --WEBRTC_FINAL_ASR_CLOUD_VERIFY_SIMILARITY "$WEBRTC_FINAL_ASR_CLOUD_VERIFY_SIMILARITY" \
  --WEBRTC_FINAL_ASR_CLOUD_VERIFY_SHORT_TEXT_CHARS "$WEBRTC_FINAL_ASR_CLOUD_VERIFY_SHORT_TEXT_CHARS" \
  --WEBRTC_FINAL_ASR_CLOUD_VERIFY_MIN_CLOUD_CHARS "$WEBRTC_FINAL_ASR_CLOUD_VERIFY_MIN_CLOUD_CHARS" \
  --WEBRTC_FINAL_ASR_CLOUD_VERIFY_REPLACE_WITH_CLOUD "$WEBRTC_FINAL_ASR_CLOUD_VERIFY_REPLACE_WITH_CLOUD" \
  --WEBRTC_ASR_SPEECH_LEVEL "$WEBRTC_ASR_SPEECH_LEVEL" \
  --WEBRTC_ASR_MIN_PARTIAL_SPEECH_FRAMES "$WEBRTC_ASR_MIN_PARTIAL_SPEECH_FRAMES" \
  --WEBRTC_ASR_MIN_FINAL_SPEECH_FRAMES "$WEBRTC_ASR_MIN_FINAL_SPEECH_FRAMES" \
  --WEBRTC_ASR_MIN_FINAL_PEAK_LEVEL "$WEBRTC_ASR_MIN_FINAL_PEAK_LEVEL" \
  --WEBRTC_ASR_DROP_WHILE_AVATAR_SPEAKING "$WEBRTC_ASR_DROP_WHILE_AVATAR_SPEAKING" \
  --WEBRTC_ASR_ECHO_GUARD_MS "$WEBRTC_ASR_ECHO_GUARD_MS" \
  --WEBRTC_ASR_ECHO_SIMILARITY "$WEBRTC_ASR_ECHO_SIMILARITY" \
  "${WEBRTC_FINAL_ASR_STRICT_ARGS[@]}" \
  "${DEEPFACE_ARGS[@]}" \
  --llm_backend "$LLM_BACKEND" \
  --LLM_CUSTOM_HANDLER "$LLM_CUSTOM_HANDLER" \
  --LIGHTRAG_ENABLE "$LIGHTRAG_ENABLE" \
  --LIGHTRAG_BASE_URL "$LIGHTRAG_BASE_URL" \
  --LIGHTRAG_USERNAME "$LIGHTRAG_USERNAME" \
  --LIGHTRAG_PASSWORD "$LIGHTRAG_PASSWORD" \
  --LIGHTRAG_TIMEOUT_S "$LIGHTRAG_TIMEOUT_S" \
  --LIGHTRAG_QUERY_MODE "$LIGHTRAG_QUERY_MODE" \
  --LIGHTRAG_TOP_K "$LIGHTRAG_TOP_K" \
  --LIGHTRAG_CHUNK_TOP_K "$LIGHTRAG_CHUNK_TOP_K" \
  --LIGHTRAG_MAX_TOTAL_TOKENS "$LIGHTRAG_MAX_TOTAL_TOKENS" \
  --ditto_root "$TALKINGHEAD_DIR" \
  --ditto_data_root "$DITTO_DATA_ROOT" \
  --ditto_cfg_pkl "$DITTO_CFG_PKL" \
  --ditto_source_path "$DITTO_SOURCE_PATH" \
  --ditto_chunksize "${DITTO_CHUNKSIZE_ARGS[@]}" \
  --turn_url "$TURN_URL" \
  --turn_host "$TURN_HOST" \
  --turn_port "$TURN_PORT" \
  --turn_tls_port "$TURN_TLS_PORT" \
  --turn_enable_udp "$TURN_ENABLE_UDP" \
  --turn_enable_tcp "$TURN_ENABLE_TCP" \
  --turn_enable_tls "$TURN_ENABLE_TLS" \
  --ice_transport_policy "$ICE_TRANSPORT_POLICY" \
  --prefer_h264 "$PREFER_H264" \
  --turn_username "$TURN_USERNAME" \
  --turn_password "$TURN_PASSWORD"
